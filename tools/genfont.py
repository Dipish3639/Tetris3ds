#!/usr/bin/env python3
"""Rasterise a TTF/OTF into anti-aliased 8-bit glyph bitmaps for source/font_data.c.

Usage: python3 tools/genfont.py path/to/Inter-ExtraBold.otf > source/font_data.c
Inter is licensed under the SIL Open Font License 1.1.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONTS = [("FONT_SMALL", 9), ("FONT_MED", 13), ("FONT_BIG", 20), ("FONT_HUGE", 34)]
CHARS = [chr(c) for c in range(32, 127)]


def build(path, name, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    _, cap_top, _, cap_bottom = font.getbbox("H")
    glyphs, bits = [], []
    for ch in CHARS:
        l, t, r, b = font.getbbox(ch)
        w, h = max(r - l, 0), max(b - t, 0)
        if ch == " ":
            w = h = 0
        off = len(bits)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255)
            bits.extend(img.tobytes())
        adv = int(round(font.getlength(ch)))
        glyphs.append((off, w, h, l, t, adv))
    out = []
    out.append(f"static const Glyph {name}_glyphs[{len(CHARS)}] = {{")
    for off, w, h, l, t, adv in glyphs:
        out.append(f"\t{{ {off}, {w}, {h}, {l}, {t}, {adv} }},")
    out.append("};")
    out.append(f"static const uint8_t {name}_bits[{max(len(bits), 1)}] = {{")
    for i in range(0, len(bits), 24):
        out.append("\t" + ",".join(str(v) for v in bits[i:i + 24]) + ",")
    if not bits:
        out.append("\t0,")
    out.append("};")
    out.append(f"const Font {name} = {{ {name}_glyphs, {name}_bits, {cap_top}, "
               f"{cap_bottom - cap_top}, {ascent + descent} }};")
    return "\n".join(out)


def main():
    path = sys.argv[1]
    print("/* Generated by tools/genfont.py from Inter ExtraBold (SIL OFL 1.1). Do not edit. */")
    print('#include "font.h"\n')
    for name, size in FONTS:
        print(build(path, name, size))
        print()


if __name__ == "__main__":
    main()
